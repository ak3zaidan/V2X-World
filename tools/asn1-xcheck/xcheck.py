"""Independent COER cross-check for the IEEE 1609.2 / 1609.2.1 bindings in `v2xw-msg`.

The Rust bindings are generated by `rasn-compiler` and encoded by `rasn`. This tool uses a
codec that shares no code with either: `asn1tools` (pure Python, its own ASN.1 parser and
its own X.696 OER encoder), compiling the *same committed module files* the Rust build
reads. It never reads any Rust.

Commands (run with the project venv, `python -I tools/asn1-xcheck/xcheck.py ...`):

  gen OUT [--n 200] [--seed 20261016]
      Draw N random, constraint-respecting values of every type in TYPES, encode each with
      asn1tools, check that asn1tools decodes it back to the same value, and write one
      `TypeName HEX` line per value. The Rust test `crates/v2xw-msg/tests/scms_coer_xcheck.rs`
      decodes every line with rasn and requires rasn's re-encoding to be byte-identical.

  verify IN
      Read `TypeName HEX` lines produced by Rust; asn1tools must decode each and re-encode
      it to the identical bytes. Prints one verdict line; exit status 0 only if all pass.

  diff-editions
      Print the code-level (comments stripped) differences between the committed 2022 and
      2025 editions of the IEEE 1609.2 modules.

Limitations, stated so nobody reads more into a green run than it says:
  * asn1tools implements BASIC-OER. For the types here the canonical (COER) rules that
    differ from BASIC-OER are minimal length/integer encodings and omission of DEFAULT
    values; asn1tools does both in root components. The comparison is byte equality in
    both directions, so any disagreement shows up as a failure rather than being hidden.
  * asn1tools 0.169 has no OER codec for open types (`EXT-TYPE.&ExtContent`). They are
    encoded here per X.696 section 30 (length determinant + contents), patched in below.
  * `WITH COMPONENTS` inner subtyping and `CONTAINING` are not enforced by asn1tools nor by
    the rasn bindings; random values may violate them. They do not change the encoding.
  * Strings are drawn from printable ASCII, so the character-vs-octet size ambiguity of
    UTF8String never arises.
"""

import binascii
import difflib
import os
import random
import re
import sys

import asn1tools
from asn1tools.codecs import constraints_checker as cc
from asn1tools.codecs import oer

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ASN = os.path.join(ROOT, 'third_party', 'asn1', 'etsi')
BUILD_RS = os.path.join(ROOT, 'crates', 'v2xw-msg', 'build.rs')

# Types cross-checked: every SPDU of docs/design/scms-real/03 section 3.2, the inner
# 1609.2.1 PDUs they carry, and the 1609.2 structures those embed.
TYPES = [
    # 1609.2.1 Protocol: the wrapper and every SPDU.
    'ScmsPdu',
    'SecurityMgmtSsp',
    'EeEcaCertRequestSpdu', 'EcaEeCertResponseSpdu',
    'EeRaCertRequestSpdu', 'RaEeCertAckSpdu', 'RaEeCertInfoSpdu', 'RaEeCertAndAcpcInfoSpdu',
    'EeRaDownloadRequestPlainSpdu', 'EeRaDownloadRequestSpdu',
    'EeRaSuccessorEnrollmentCertRequestSpdu', 'RaEeEnrollmentCertAckSpdu',
    'RaAcaCertRequestSpdu', 'AcaRaCertResponseSpdu',
    'AcaEeCertResponsePlainSpdu', 'AcaEeCertResponsePrivateSpdu', 'AcaEeCertResponseCubkSpdu',
    'CompositeCrlSpdu', 'CertificateChainSpdu', 'MultiSignedCtlSpdu', 'CtlSignatureSpdu',
    'CertificateManagementInformationStatusSpdu',
    # Inner PDUs.
    'EeRaCertRequest', 'RaEeCertAck', 'RaEeCertInfo', 'EeRaDownloadRequest',
    'EeEcaCertRequest', 'EcaEeCertResponse', 'AcaEeCertResponse',
    'RaAcaCertRequest', 'AcaRaCertResponse', 'EncryptedIndividualPLV',
    'CertManagementPdu', 'FullIeeeTbsCtl', 'ToBeSignedCtlSignature',
    'CertificateManagementInfoStatus', 'CompositeCrl', 'CertificateChain',
    # IEEE 1609.2.
    'Ieee1609Dot2Data', 'Certificate', 'ToBeSignedCertificate', 'SignedData', 'HeaderInfo',
    'SecuredCrl', 'CrlContents',
]


def security_sources():
    """The SECURITY unit's source list, read from build.rs so it cannot drift."""
    text = open(BUILD_RS, encoding='utf-8').read()
    block = text[text.index('const SECURITY: Unit'):]
    block = block[:block.index('};')]
    return [os.path.join(ASN, s) for s in re.findall(r'"([^"]+\.asn)"', block)]


def _is_open_type(type_descriptor):
    # `EXT-TYPE.&ExtContent(...)` arrives as 'OpenType'; a field of a class asn1tools does
    # not resolve (`IEEE1609DOT2-HEADERINFO-CONTRIBUTED-EXTENSION.&Extn`) keeps its name.
    t = type_descriptor['type']
    return t == 'OpenType' or '.&' in t


def _as_octet_string(type_descriptor):
    # Same descriptor (so the automatic tag, e.g. [0] in a CHOICE, is kept) with the type
    # replaced: an OER open type is a length determinant + the inner encoding, which is
    # exactly an unconstrained OCTET STRING's encoding.
    d = dict(type_descriptor)
    d['type'] = 'OCTET STRING'
    d.pop('restricted-to', None)
    d.pop('size', None)
    return d


class _OerCompiler(oer.Compiler):
    """asn1tools' OER compiler plus X.696 section 30 open types."""

    def compile_type(self, name, type_descriptor, module_name):
        if _is_open_type(type_descriptor):
            type_descriptor = _as_octet_string(type_descriptor)
        return super().compile_type(name, type_descriptor, module_name)


class _CheckCompiler(cc.Compiler):
    def compile_type(self, name, type_descriptor, module_name):
        if _is_open_type(type_descriptor):
            type_descriptor = _as_octet_string(type_descriptor)
        return super().compile_type(name, type_descriptor, module_name)


def compile_specs(sources):
    for s in sources:
        if '[[' in open(s, encoding='utf-8').read():
            raise SystemExit('%s uses an addition group; asn1tools OER flattens those' % s)
    parsed = asn1tools.parse_files(sources, encoding='utf-8')
    enc = _OerCompiler(parsed, numeric_enums=False).process()
    chk = _CheckCompiler(parsed).process()
    return enc, chk


def find_type(table, name):
    hits = [(m, t[name]) for m, t in table.items() if name in t]
    if len(hits) != 1:
        raise SystemExit('type %s found in %d modules' % (name, len(hits)))
    return hits[0][1]


def unwrap(t):
    while isinstance(t, (oer.Recursive, cc.Recursive)):
        t = t.inner
    return t


def same_as_default(member, value):
    d = member.default
    u = unwrap(member)
    if isinstance(u, oer.BitString) and isinstance(d, tuple) and u.number_of_bits:
        n = u.number_of_bits
        bits = int.from_bytes(d[0], 'big') >> (8 * len(d[0]) - d[1]) if d[1] else 0
        padded = (bits << (n - d[1])).to_bytes((n + 7) // 8, 'big')
        return value == (padded, n)
    return value == d


class Gen:
    """Random constraint-respecting values, walking the OER and checker trees together."""

    def __init__(self, rng, max_depth=5):
        self.rng = rng
        self.max_depth = max_depth
        # Whether the value being drawn has a SEQUENCE extension addition present inside
        # another present extension addition (see NESTED in the corpus format).
        self.in_addition = 0
        self.nested_addition = False

    def value(self, t, c, depth):
        t, c = unwrap(t), unwrap(c)
        r = self.rng
        deep = depth >= self.max_depth
        if isinstance(t, (oer.Sequence, oer.Set)):
            out = {}
            members = list(t.root_members) + list(t.additions or [])
            cmembers = {m.name: m for m in c.members}
            root = set(id(m) for m in t.root_members)
            # No module in the unit uses `[[ ]]` addition groups (asn1tools would flatten
            # them); compile_specs refuses sources that do.
            for m in members:
                # A mandatory extension addition (FullIeeeTbsCtl.quorum) is mandatory in
                # every value of this version of the type, like a root component.
                optional = m.optional or m.default is not None
                if optional and (deep or r.random() < 0.4):
                    continue
                is_addition = id(m) not in root
                if is_addition and self.in_addition:
                    self.nested_addition = True
                self.in_addition += is_addition
                v = self.value(m, cmembers[m.name], depth + 1)
                self.in_addition -= is_addition
                if m.default is not None and same_as_default(m, v):
                    # COER (X.696 canonical) omits a component equal to its DEFAULT;
                    # asn1tools' BASIC-OER would encode it (and compares a named-bit
                    # default such as `eeType DEFAULT {app}` at its unpadded length).
                    continue
                out[m.name] = v
            return out
        if isinstance(t, oer.Choice):
            members = list(t.root_members) + list(t.additions or [])
            cmembers = {m.name: m for m in c.members}
            if deep:
                members = sorted(members, key=lambda m: self.cost(m, set()))[:1]
            m = r.choice(members)
            # A CHOICE extension alternative is also encoded as an open type.
            is_addition = any(m is a for a in (t.additions or []))
            if is_addition and self.in_addition:
                self.nested_addition = True
            self.in_addition += is_addition
            v = self.value(m, cmembers[m.name], depth + 1)
            self.in_addition -= is_addition
            return (m.name, v)
        if isinstance(t, (oer.SequenceOf, oer.SetOf)):
            lo = c.minimum if c.has_lower_bound() else 0
            hi = c.maximum if c.has_upper_bound() else lo + 3
            hi = min(hi, lo + (0 if deep else 2))
            n = r.randint(lo, hi)
            return [self.value(t.element_type, c.element_type, depth + 1) for _ in range(n)]
        if isinstance(t, oer.Integer):
            return self.integer(c)
        if isinstance(t, oer.Boolean):
            return r.random() < 0.5
        if isinstance(t, oer.Null):
            return None
        if isinstance(t, oer.Enumerated):
            return r.choice(sorted(t.data_to_value))
        if isinstance(t, oer.BitString):
            if t.number_of_bits is not None:
                n = t.number_of_bits
            else:
                lo = c.minimum if c.has_lower_bound() else 0
                hi = c.maximum if c.has_upper_bound() else lo + 24
                n = r.randint(lo, min(hi, lo + 24))
            v = r.getrandbits(n) if n else 0
            nbytes = (n + 7) // 8
            raw = (v << (8 * nbytes - n)).to_bytes(nbytes, 'big') if n else b''
            return (raw, n)
        if isinstance(t, oer.OctetString):
            if t.number_of_bytes is not None:
                n = t.number_of_bytes
            else:
                lo = c.minimum if c.has_lower_bound() else 0
                hi = c.maximum if c.has_upper_bound() else lo + 40
                n = r.randint(lo, min(hi, lo + 24))
                if r.random() < 0.05 and (not c.has_upper_bound() or c.maximum >= 200):
                    n = max(n, 200)      # exercise the long-form length determinant
            return bytes(r.getrandbits(8) for _ in range(n))
        if isinstance(t, oer.KnownMultiplierStringType):
            lo = c.minimum if c.has_lower_bound() else 0
            hi = c.maximum if c.has_upper_bound() else lo + 20
            n = r.randint(lo, min(hi, lo + 20))
            return ''.join(chr(r.randint(0x20, 0x7e)) for _ in range(n))
        raise SystemExit('no generator for %r (%s)' % (type(t).__name__, t.name))

    def integer(self, c):
        r = self.rng
        lo = c.minimum if c.has_lower_bound() else None
        hi = c.maximum if c.has_upper_bound() else None
        if lo is not None and hi is not None:
            pick = r.random()
            if pick < 0.15:
                return lo
            if pick < 0.3:
                return hi
            return r.randint(lo, hi)
        base = lo if lo is not None else 0
        # Capped at 63 bits: rasn 0.28.14 encodes a non-negative semi-constrained INTEGER
        # (`Psid ::= INTEGER (0..MAX)`) of 2^63 or more with a spurious leading 0x00
        # (`Integer::to_unsigned_bytes_be` calls `to_signed_bytes_be` for big values).
        # The defect is pinned by `rasn_defect_psid_at_or_above_2_pow_63` in
        # crates/v2xw-msg/tests/scms_coer_xcheck.rs; lift this cap when that test flips.
        bits = r.choice([0, 1, 7, 8, 9, 15, 16, 17, 31, 32, 33, 56, 62, 63])
        v = base + (r.getrandbits(bits) if bits else 0)
        if lo is None and hi is None and r.random() < 0.5:
            v = -v
        if hi is not None and v > hi:
            v = hi
        return v

    def cost(self, t, seen):
        """Minimal nesting needed to finish a value of `t`; recursion is infinite."""
        key = id(t)
        if key in seen:
            return float('inf')
        seen = seen | {key}
        u = unwrap(t)
        if isinstance(u, oer.Recursive):
            return float('inf')
        if isinstance(u, (oer.Sequence, oer.Set)):
            root = [m for m in u.root_members if not (m.optional or m.default is not None)]
            return 1 + max([self.cost(m, seen) for m in root] or [0])
        if isinstance(u, oer.Choice):
            return 1 + min(self.cost(m, seen) for m in list(u.root_members) + list(u.additions or []))
        if isinstance(u, (oer.SequenceOf, oer.SetOf)):
            return 1
        return 0


def gen(out_path, n, seed):
    enc, chk = compile_specs(security_sources())
    rng = random.Random(seed)
    g = Gen(rng)
    lines = []
    for name in TYPES:
        t, c = find_type(enc, name), find_type(chk, name)
        for made in range(n):
            g.nested_addition = False
            v = g.value(t.type, c.type, 0)
            # No rejection sampling: a value the generator thinks valid but asn1tools'
            # constraint checker or encoder refuses is a generator bug, and silently
            # skipping it would bias the corpus towards whatever happens to encode.
            c.encode(v)
            raw = t.encode(v)
            back = t.decode(raw)
            if t.encode(back) != raw:
                raise SystemExit('%s: asn1tools is not self-consistent' % name)
            flag = ' NESTED' if g.nested_addition else ''
            lines.append('%s %s%s' % (name, binascii.hexlify(raw).decode(), flag))
    header = [
        '# COER cross-check corpus: values drawn and encoded by asn1tools %s' % asn1tools.__version__,
        '# generator: tools/asn1-xcheck/xcheck.py gen --n %d --seed %d' % (n, seed),
        '# sources: the SECURITY unit of crates/v2xw-msg/build.rs (%d modules)' % len(security_sources()),
        '# types: %d, values per type: %d' % (len(TYPES), n),
        '# format: TYPE HEX [NESTED]; NESTED = a SEQUENCE extension addition is present inside',
        '#   another present extension addition (the rasn 0.28 encoder defect, see the Rust test)',
    ]
    with open(out_path, 'w') as f:
        f.write('\n'.join(header + lines) + '\n')
    print('gen: %d values of %d types written' % (len(lines), len(TYPES)))


def verify(in_path):
    enc, chk = compile_specs(security_sources())
    total, bad = 0, []
    per = {}
    for line in open(in_path):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        name, hx = line.split()[:2]
        raw = binascii.unhexlify(hx)
        total += 1
        per[name] = per.get(name, 0) + 1
        try:
            t = find_type(enc, name)
            again = t.encode(t.decode(raw))
            if again != raw:
                bad.append('%s: re-encoding differs' % name)
        except Exception as e:
            bad.append('%s: %s' % (name, str(e)[:120]))
    verdict = 'PASS' if total and not bad else 'FAIL'
    print('verify: %s %d values, %d types, %d failures' % (verdict, total, len(per), len(bad)))
    for b in bad[:10]:
        print('  ' + b)
    return 0 if verdict == 'PASS' else 1


def code_lines(path):
    text = open(path, 'rb').read().decode('cp1252')
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'--.*?(--|$)', '', text, flags=re.M)
    return [' '.join(l.split()) for l in text.splitlines() if l.strip()]


def diff_editions():
    for m in ['Ieee1609Dot2', 'Ieee1609Dot2BaseTypes', 'Ieee1609Dot2Crl', 'Ieee1609Dot2CrlBaseTypes']:
        a = code_lines(os.path.join(ASN, 'ieee1609.2-2022', m + '.asn'))
        b = code_lines(os.path.join(ASN, 'ieee1609.2', m + '.asn'))
        d = [l for l in difflib.unified_diff(a, b, lineterm='', n=0) if l[:1] in '+-' and l[:3] not in ('---', '+++')]
        print('%s: %d changed code lines' % (m, len(d)))
        for l in d:
            print('  ' + l)


def main(argv):
    if len(argv) >= 2 and argv[0] == 'gen':
        n, seed = 200, 20261016
        if '--n' in argv:
            n = int(argv[argv.index('--n') + 1])
        if '--seed' in argv:
            seed = int(argv[argv.index('--seed') + 1])
        gen(argv[1], n, seed)
        return 0
    if len(argv) == 2 and argv[0] == 'verify':
        return verify(argv[1])
    if argv == ['diff-editions']:
        diff_editions()
        return 0
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
