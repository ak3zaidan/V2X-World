#!/usr/bin/env python3
"""samples_doc.py <release root> <out.md> [--repo org/name]: write docs/dataset/samples.md.

What the release is, its layout, three real rows of each main table, and one revoked
attacker followed through every stage (truth -> air -> neighbour's check -> report -> MA ->
decision -> CRL -> timeline). Reads only the release; no clock, no randomness.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import pyarrow.dataset as ds

MAIN = ["local/rx", "local/ego", "local/checks", "local/reports", "local/pki",
        "global/reports", "global/decisions", "global/crl",
        "truth/transmissions", "truth/receptions", "truth/devices", "truth/reports",
        "truth/timeline"]


def span(v: pd.Series, unit: str) -> str:
    """`75 s`, or `60-75 s` when the runs differ."""
    lo, hi = float(v.min()), float(v.max())
    return f"{lo:.0f}{unit}" if lo == hi else f"{lo:.0f}-{hi:.0f}{unit}"


def load(root: Path, t: str) -> pd.DataFrame:
    p = root / t
    if not p.is_dir():
        return pd.DataFrame()
    return ds.dataset(str(p), format="parquet", partitioning="hive").to_table().to_pandas()


def clean(v):
    if hasattr(v, "tolist"):
        v = v.tolist()
    if isinstance(v, float):
        return None if v != v else round(v, 4)
    if isinstance(v, list):
        return [clean(x) for x in v[:3]] + (["..."] if len(v) > 3 else [])
    if isinstance(v, dict):
        return {k: clean(x) for k, x in v.items()}
    return v


def rows_json(df: pd.DataFrame, n: int = 3) -> str:
    out = []
    for _, r in df.head(n).iterrows():
        out.append(json.dumps({k: clean(v) for k, v in r.items() if k not in ("split", "run")},
                              default=str))
    return "```json\n" + "\n".join(out) + "\n```\n"


def one(df: pd.DataFrame) -> str:
    if df.empty:
        return "_(no row)_\n"
    r = df.iloc[0]
    return "```json\n" + json.dumps({k: clean(v) for k, v in r.items()
                                     if k not in ("split", "run")}, indent=1, default=str) \
        + "\n```\n"


def sec(ns) -> str:
    return "-" if ns is None or ns != ns else f"{ns / 1e9:.3f} s"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("root", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--repo", default="akzaidan/v2x-scms-mbd-mini")
    a = ap.parse_args(argv)
    root = a.root
    runs = pd.read_parquet(root / "runs.parquet")
    T = {t: load(root, t) for t in MAIN}
    L = ["# V2X-SCMS-MBD mini release: samples\n",
         f"Generated by `tools/dataset/samples_doc.py` from the assembled release published "
         f"as [{a.repo}](https://huggingface.co/datasets/{a.repo}). Every value below is a "
         "real row of that release.\n",
         "## What it is\n",
         f"{len(runs)} simulated run{'' if len(runs) == 1 else 's'} of "
         f"{span(runs['duration_s'], ' s')}, {span(runs['vehicles'].astype(int), '')} vehicles"
         f"{'' if len(runs) == 1 else ' each'}, on a procedural street grid with "
         "the US SCMS in the loop. Each run is published from three sides: what each "
         "vehicle's OBU saw (`local/`), what the Misbehavior Authority saw (`global/`), and "
         "the ground truth (`truth/`), kept apart so no label sits next to a feature. "
         "Splits are per run: "
         + ", ".join(f"{s}: {', '.join(runs.loc[runs.split == s, 'run_id'])}"
                     for s in ("train", "validation", "test") if (runs.split == s).any())
         + (" (one split: no validation or test run, nothing held out)"
            if runs.split.nunique() == 1 else "") + ".\n",
         "## Layout\n",
         "```",
         "README.md  croissant.json  manifest.json  runs.parquet",
         "schema/<view>_<table>.json             column contract",
         "<view>/<table>/split=<s>/run=<id>/part-00000.parquet",
         "  local/  rx ego checks reports pki",
         "  global/ reports decisions crl",
         "  truth/  transmissions receptions devices pseudonyms reports timeline app_effects",
         "  ml/     local global                 (joined with labels, training only)",
         "compat/veremi/<run>.zip  compat/dare/<run>.zip  scenarios/<run>.yaml",
         "```\n",
         "| table | rows |", "|---|---|"]
    for t in MAIN:
        L.append(f"| `{t}` | {len(T[t]):,} |")
    L += ["", "## Three rows of each main table\n"]
    for t in MAIN:
        df = T[t]
        if df.empty:
            continue
        if t in ("truth/transmissions", "truth/receptions", "truth/devices"):
            df = pd.concat([df[df["label"] == "malicious"].head(2), df[df["label"] != "malicious"].head(1)])
        elif t == "local/rx":
            df = pd.concat([df[df["verify_result"] != "ok"].head(1), df.head(2)])
        L += [f"### `{t}`\n", rows_json(df)]

    # one revoked attacker through every stage
    tl, dec, crl = T["truth/timeline"], T["global/decisions"], T["global/crl"]
    pick = tl[(tl["label"] == "malicious") & tl["decision_ns"].notna()
              & tl["crl_published_ns"].notna()].sort_values(["run_id", "device_id"])
    L.append("## One attacker followed through every stage\n")
    if pick.empty:
        L.append("No attacker in this release was revoked.\n")
    else:
        t0 = pick.iloc[0]
        run, dev = t0["run_id"], int(t0["device_id"])
        devs = T["truth/devices"]
        d = devs[(devs.run_id == run) & (devs.device_id == dev)]
        ps = load(root, "truth/pseudonyms")
        certs = set(ps[(ps.run_id == run) & (ps.device_id == dev)]["cert_id"])
        tx = T["truth/transmissions"]
        mtx = tx[(tx.run_id == run) & (tx.device_id == dev) & (tx.label == "malicious")] \
            .sort_values("t_ns")
        rcp = T["truth/receptions"]
        rx = T["local/rx"]
        rr = rcp[(rcp.run_id == run) & rcp.tx_id.isin(set(mtx.tx_id))]
        rx1 = rx[(rx.run_id == run) & rx.rx_id.isin(set(rr.rx_id))].sort_values("t_rx_ns")
        lrep = T["local/reports"]
        lr = lrep[(lrep.run_id == run) & lrep.subject_cert_id.isin(certs)].sort_values("t_created_ns")
        chk = T["local/checks"]
        ck = chk[(chk.run_id == run) & chk.cert_id.isin(certs)].sort_values("t_ns")
        grep_ = T["global/reports"]
        gr = grep_[(grep_.run_id == run) & grep_.subject_cert_id.isin(certs)].sort_values("t_received_ns")
        dd = dec[(dec.run_id == run) & (dec.subject_cert_id.isin(certs)
                                        | dec.la_link.isin(set(gr.la_link.dropna())))]
        cr = crl[(crl.run_id == run) & crl.la_link.isin(set(dd.la_link.dropna()))]
        tr = T["truth/reports"]
        trr = tr[(tr.run_id == run) & tr.report_id.isin(set(gr.report_id))]
        L += [f"Device {dev} in run {run} (`{d['attack_id'].iloc[0]}`), "
              f"{len(certs)} pseudonym certificate(s), {len(mtx):,} malicious transmissions, "
              f"{len(rx1):,} receptions of them by the instrumented OBUs; "
              f"{len(lr)} reports filed against it, {len(gr)} reached the MA.\n",
              "| stage | time | where |", "|---|---|---|",
              f"| attack starts | {sec(t0['attack_start_ns'])} | `truth/devices`, `truth/timeline` |",
              f"| first falsified BSM on the air | {sec(t0['first_falsified_ns'])} | `truth/transmissions` |",
              f"| first received by an instrumented OBU | {sec(rx1['t_rx_ns'].iloc[0]) if len(rx1) else '-'} | `local/rx` |",
              f"| first detection | {sec(t0['first_detection_ns'])} | `local/checks` |",
              f"| first report created | {sec(t0['first_report_created_ns'])} | `local/reports` |",
              f"| first report uploaded | {sec(t0['first_report_uploaded_ns'])} | `local/reports.t_uploaded_ns` |",
              f"| first report at the MA | {sec(t0['first_report_at_ma_ns'])} | `global/reports` |",
              f"| MA decision | {sec(t0['decision_ns'])} | `global/decisions` |",
              f"| CRL published | {sec(t0['crl_published_ns'])} | `global/crl` |",
              f"| CRL at first / median / p95 neighbour | {sec(t0['crl_first_neighbour_ns'])} / "
              f"{sec(t0['crl_median_neighbour_ns'])} / {sec(t0['crl_p95_neighbour_ns'])} | `local/pki` |",
              f"| last malicious message accepted | {sec(t0['last_malicious_accepted_ns'])} | `truth/timeline` |",
              "",
              "**1. Truth: the device** (`truth/devices`)\n", one(d),
              "**2. Its first falsified transmission** (`truth/transmissions`)\n", one(mtx),
              "**3. A neighbour OBU receives it** (`local/rx`; the label is only in "
              "`truth/receptions`, joined on `rx_id`)\n", one(rx1),
              one(rr[rr.rx_id.isin(set(rx1.rx_id.head(1)))]),
              "**4. A neighbour's check fires** (`local/checks`)\n", one(ck),
              "**5. The neighbour files a report** (`local/reports`)\n", one(lr),
              "**6. The MA receives the MBR** (`global/reports`)\n", one(gr),
              "**7. Its verdict** (`truth/reports`)\n", one(trr),
              "**8. The MA decides** (`global/decisions`)\n", one(dd),
              "**9. The CRL entry** (`global/crl`)\n", one(cr),
              "**10. The whole timeline** (`truth/timeline`)\n", one(pick.head(1))]
    a.out.write_text("\n".join(L))
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
