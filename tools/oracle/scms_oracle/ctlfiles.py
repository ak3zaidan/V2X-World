"""CTL files of an F1 capture (``gov.json``): elector verification and installation order.

``oracle.py ctl-files GOV_JSON [--mutate]``.  Rules from the [ASN-2.1] CertManagement text
(tools/oracle/asn1/ieee1609.2.1-2022/Ieee1609Dot2Dot1CertManagement.asn):
  * sequenceNumber "is incremented by 1 every time a new FullIeeeTbsCtl is issued";
  * effectiveDate "is to be greater than or equal to the effectiveDate field in the CTL with the
    same CtlSeriesId and the previous sequence number";
  * quorum is "the number of the electors required to sign the next CTL with the same CtlSeriesId
    value for that CTL to be trusted" (absent: the current quorum carries over);
  * "Any root CA or elector certificate that is not on the CTL is not trusted"; electors are
    listed by the hash "used to hash the elector certificate for signing";
  * signatures: "no more than the number of electors. Each signature shall have been generated by
    a distinct elector"; each CtlSignatureSpdu signs {ctlSeriesId, ctlType, sequenceNumber,
    tbsCtlHash = H(C-OER tbsCtl)} under PSID 35; US CtlSeriesId 0348000000000000 (03 sec. 10).
A device installs CTL n+1 only when it holds CTL n (its electors and quorum decide n+1).
"""

import copy

from . import certs, coer, prims
from .records import SECMGMT_PSID, Rules, payload_bytes, signed

US_CTL_SERIES = bytes.fromhex('0348000000000000')


def _parts(hx):
    outer = coer.decode('Ieee1609Dot2Data', bytes.fromhex(hx))
    pdu = coer.decode('ScmsPdu', outer['content'][1])
    kind, m = pdu['content'][1]
    if kind != 'multiSignedCtl':
        raise ValueError(kind)
    return m, coer.decode('FullIeeeTbsCtl', m['tbsCtl'])


def check(gov):
    X = Rules(None)
    for g in gov:
        # a provider may hold one CTL several times (history, current, pending): every
        # distinct encoding is checked, and the copies of one sequence number must agree
        copies = {}
        for c in g['ctls']:
            hs = copies.setdefault(c['sequence'], [])
            if c['hex'] not in hs:
                hs.append(c['hex'])
        for seq, hs in copies.items():
            X.check('CTL-FILE', len(hs) == 1,
                    f'{g["provider"]}/ctl/{seq}: {len(hs)} different encodings of one sequence number')
        prev = None
        for seq, k, hx in [(q, k, hx) for q in sorted(copies) for k, hx in enumerate(copies[q])]:
            w = f'{g["provider"]}/ctl/{seq}' + (f' copy {k}' if len(copies[seq]) > 1 else '')
            m, tbs = _parts(hx)
            X.check('CTL-FILE', tbs['sequenceNumber'] == seq, w + ': sequenceNumber')
            X.check('CTL-FILE', tbs['ctlSeriesId'] == US_CTL_SERIES, w + f': series {tbs["ctlSeriesId"].hex()}')
            approve = tbs['electorApprove'] if prev is None else prev[1]['electorApprove']
            # the genesis CTL is installed out of band; the published US genesis CTLs (sequence
            # 0, 2023) carry no quorum, so the quorum for CTL 1 is then not stated (None: at
            # least one valid approved signature is required, and the count is reported)
            quorum = tbs.get('quorum') if prev is None else prev[1].get('quorum', prev[2])
            X.check('CTL-FILE', len(m['signatures']) <= len(approve), w + ': more signatures than electors')
            good = set()
            for n, sig in enumerate(m['signatures']):
                sd = signed(sig)
                if not X.check('CTL-SIG', sd is not None and sd['signer'][0] == 'certificate',
                               w + f' sig {n}: not signed by a certificate'):
                    continue
                el = sd['signer'][1][0]
                hi = sd['tbsData']['headerInfo']
                X.check('CTL-SIG', hi.get('psid') == SECMGMT_PSID, w + f' sig {n}: psid {hi.get("psid")}')
                X.check('CTL-SIG', certs.verify_explicit(el, None), w + f' sig {n}: elector self-signature')
                C, Q = certs.verification_key(el)
                hname = certs.HASH_OF_CURVE[C.name]
                digest = prims.digest_1609(hname, coer.encode('ToBeSignedData', sd['tbsData']), certs.encode_canonical(el))
                r, s = certs.sig_rs(sd['signature'])
                ok = prims.ecdsa_verify(C, Q, digest, r, s)
                X.check('CTL-SIG', ok, w + f' sig {n}: signature')
                ts = coer.decode('ScmsPdu', payload_bytes(sd))['content'][1][1]
                hfn = prims.HASHES[hname]
                X.check('CTL-SIG', ts['ctlSeriesId'] == tbs['ctlSeriesId'] and ts['sequenceNumber'] == seq
                        and ts['tbsCtlHash'] == hfn(m['tbsCtl']), w + f' sig {n}: ToBeSignedCtlSignature fields')
                eh = hfn(certs.encode_canonical(el))
                trusted = eh in approve
                X.check('CTL-SIG', trusted, w + f' sig {n}: elector {eh.hex()[:16]} not approved by '
                                               f'{"itself" if prev is None else "the previous CTL"}')
                if ok and trusted:
                    X.check('CTL-SIG', eh not in good, w + f' sig {n}: elector signed twice')
                    good.add(eh)
            X.check('CTL-QUORUM', len(good) >= (quorum if quorum is not None else 1),
                    w + f': {len(good)} valid approved signatures < quorum {quorum}')
            X.info[w] = f'{len(good)}/{len(m["signatures"])} valid approved signatures, quorum {quorum}'
            if prev is None:
                # the genesis CTL also has to approve its own signers' quorum
                X.check('CTL-QUORUM', len(good) >= (tbs.get('quorum') or 1), w + ': genesis below its own quorum')
            if prev is not None:
                X.check('CTL-ORDER', seq == prev[0] + 1, w + f': sequence {prev[0]} -> {seq}')
                X.check('CTL-ORDER', tbs['effectiveDate'] >= prev[1]['effectiveDate'], w + ': effectiveDate decreases')
            if k == len(copies[seq]) - 1:
                # the next sequence number is checked against this one (its first copy when
                # the copies disagree, which CTL-FILE reports)
                prev = (seq, _parts(copies[seq][0])[1] if k else tbs, quorum)
    return X


def _reenc(hx, fn):
    outer = coer.decode('Ieee1609Dot2Data', bytes.fromhex(hx))
    pdu = coer.decode('ScmsPdu', outer['content'][1])
    m = pdu['content'][1][1]
    fn(m)
    outer['content'] = ('unsecuredData', coer.encode('ScmsPdu', pdu))
    return coer.encode('Ieee1609Dot2Data', outer).hex()


def _newest(gov):
    g = max(gov, key=lambda g: len(g['ctls']))
    return g, max(g['ctls'], key=lambda c: c['sequence'])


def _drop_sigs(m):
    m['signatures'] = m['signatures'][:1]


def _dup_sig(m):
    m['signatures'] = [m['signatures'][0]] * len(m['signatures'])


def _flip_sig(m):
    sd = m['signatures'][0]['content'][1]
    s = sd['signature'][1]
    s['sSig'] = bytes([s['sSig'][0] ^ 1]) + s['sSig'][1:]


def _tbs(fn):
    def f(m):
        t = coer.decode('FullIeeeTbsCtl', m['tbsCtl'])
        fn(t)
        m['tbsCtl'] = coer.encode('FullIeeeTbsCtl', t)
    return f


FAULTS = {
    'ctl-one-signature': ('the newest CTL keeps one signature', 'CTL-QUORUM', lambda gov: _mut(gov, _drop_sigs)),
    'ctl-same-elector': ('every signature is the same elector', 'CTL-QUORUM', lambda gov: _mut(gov, _dup_sig)),
    'ctl-sig-flip': ('an elector signature bit flipped', 'CTL-SIG', lambda gov: _mut(gov, _flip_sig)),
    'ctl-tbs-edited': ('tbsCtl changed after signing (root list edited)', 'CTL-SIG',
                       lambda gov: _mut(gov, _tbs(lambda t: t.update(rootCaApprove=t['rootCaApprove'][:-1])))),
    'ctl-skip-seq': ('the newest CTL numbered two past the previous', 'CTL-ORDER', lambda gov: _skip(gov)),
    'ctl-copy-differs': ('one copy of a CTL the provider holds twice differs', 'CTL-FILE', lambda gov: _one_copy(gov)),
}


def _same(g, c):
    """Every copy of c in g (a provider holds one CTL both in its history and as current)."""
    return [x for x in g['ctls'] if x['sequence'] == c['sequence'] and x['hex'] == c['hex']]


def _mut(gov, fn):
    g, c = _newest(gov)
    new = _reenc(c['hex'], fn)
    for x in _same(g, c):
        x['hex'] = new
    return True


def _skip(gov):
    g, c = _newest(gov)
    if len({x['sequence'] for x in g['ctls']}) < 2:
        return False
    new = _reenc(c['hex'], _tbs(lambda t: t.update(sequenceNumber=t['sequenceNumber'] + 1)))
    for x in _same(g, c):
        x['sequence'] += 1
        x['hex'] = new
    return True


def _one_copy(gov):
    """Only one of several copies of the newest CTL is altered (a signature bit)."""
    g, c = _newest(gov)
    if len(_same(g, c)) < 2:
        return False
    c['hex'] = _reenc(c['hex'], _flip_sig)
    return True


def mutate(gov):
    base = {r: len(f) for r, f in check(gov).bad.items()}
    out = []
    for name, (desc, rule, fn) in FAULTS.items():
        G = copy.deepcopy(gov)
        if not fn(G):
            out.append((name, rule, 'n/a'))
            continue
        X = check(G)
        out.append((name, rule, 'red' if len(X.bad.get(rule, [])) > base.get(rule, 0) else 'SILENT'))
    return out
