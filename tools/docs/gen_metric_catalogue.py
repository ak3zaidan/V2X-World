#!/usr/bin/env python3
"""Generate the metric catalogue page from the engine's metric definitions.

Usage:

    cargo run -q -p v2xw-engine --example dump_metrics -- --out target/docs-metrics.json
    python3 tools/docs/gen_metric_catalogue.py target/docs-metrics.json [--out docs/metrics/catalogue.md]

The input is every `MetricDef` the engine's provider selection can install
(crates/v2xw-engine/examples/dump_metrics.rs), each tagged with the `metrics:` selection
that installs it. Nothing here names a metric: names, units, aggregations, visibility,
definitions, sources and what each metric leaves out all come from the input.

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path
from sanitize import sanitize  # drops pointers to unpublished working notes

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO / "docs" / "metrics" / "catalogue.md"

BANNER = (
    "<!-- GENERATED by tools/docs/gen_metric_catalogue.py from the engine's metric "
    "definitions (crates/v2xw-engine/examples/dump_metrics.rs). Do not edit by hand: "
    "change the engine and run `just docs-gen`. -->\n"
)

# How each selection is explained; the keys are the dumper's `selected_by` values.
SELECTION_TEXT = OrderedDict(
    [
        ("all", "Installed by `metrics: [all]`, or by naming any of the provider's metrics."),
        (
            "all, on a run with a security path",
            "Installed by `metrics: [all]` (or by name) when the run has a security path: a "
            "backend or security protocol, roadside units, attackers or local detectors.",
        ),
        (
            "all, with apps.enabled",
            "Installed by `metrics: [all]` (or by name) when `apps.enabled` lists at least "
            "one application.",
        ),
        (
            "an energy section",
            "Installed when the scenario has an `energy:` section, or when the metric list "
            "names one of these metrics. Not part of a bare `all`.",
        ),
        ("signing", "Opt-in: `metrics: [all, signing]`, or any `sig_*` name. Not part of a bare `all`."),
        ("traffic", "Installed with a `traffic:` section, or with `metrics: [all, traffic]` or one of these names."),
        (
            "detection-scores",
            "Opt-in: `metrics: [all, detection-scores]` or one of these names; naming it also "
            "records the detectors' `det.observation`.",
        ),
        ("ssm", "Opt-in: `metrics: [all, ssm]`, or any `ssm_*` name: the full surrogate safety measures."),
        (
            None,
            "Defined in `v2xw_metrics::runtime` and installed by `v2xw_metrics::register_all`, "
            "but **not installed in an engine run**: the engine reads no clock. Diagnostic, "
            "excluded from every digest.",
        ),
    ]
)

SELECTION_TITLE = {
    "all": "Core metrics (`all`)",
    "all, on a run with a security path": "Credential and privacy metrics (`all`, security path)",
    "all, with apps.enabled": "Application metrics (`all`, applications enabled)",
    "an energy section": "Energy and emissions (`energy`)",
    "signing": "Signing overhead (`signing`)",
    "traffic": "Traffic control (`traffic`)",
    "detection-scores": "Detection scores (`detection-scores`)",
    "ssm": "Surrogate safety measures (`ssm`)",
    None: "Runtime diagnostics (library only)",
}


def cell(text: str) -> str:
    """One line of Markdown safe inside a table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def fmt_agg(agg) -> str:
    if isinstance(agg, str):
        return agg
    if isinstance(agg, dict) and "numerator" in agg and "denominator" in agg:
        return f"{agg.get('kind', 'ratio')}: {agg['numerator']} / {agg['denominator']}"
    if isinstance(agg, dict) and set(agg) == {"kind"}:
        return str(agg["kind"])
    if isinstance(agg, dict):
        if len(agg) == 1:
            (k, v), = agg.items()
            if isinstance(v, dict):
                if "num" in v and "den" in v:
                    return f"{k}: {v['num']} / {v['den']}"
                inner = ", ".join(f"{a}={b}" for a, b in v.items())
                return f"{k} ({inner})"
            if isinstance(v, list):
                return f"{k} ({', '.join(map(str, v))})"
            return f"{k} ({v})"
        kind = agg.get("kind") or agg.get("type")
        rest = {a: b for a, b in agg.items() if a not in ("kind", "type")}
        if kind and "num" in rest and "den" in rest:
            return f"{kind}: {rest['num']} / {rest['den']}"
        inner = ", ".join(f"{a}={b}" for a, b in rest.items())
        return f"{kind} ({inner})" if kind else inner
    return json.dumps(agg)


def fmt_dims(dims) -> str:
    if not dims:
        return ""
    out = []
    for d in dims:
        if isinstance(d, str):
            out.append(d)
        elif isinstance(d, dict):
            out.append(str(d.get("name") or d.get("kind") or next(iter(d.values()), "")))
        else:
            out.append(str(d))
    return ", ".join(f"`{d}`" for d in out)


PATH_REF = re.compile(r"(?:^|\s)((?:docs|crates|tools|tests|worlds|scenarios)/[^\s:;,)]+)")


def fmt_source(src) -> str:
    """The source, or nothing when it cites a repository file that is not in the repository
    (a working note kept outside the published tree)."""
    if not src:
        return ""
    if isinstance(src, dict):
        ref = src.get("ref", "")
        for path in PATH_REF.findall(ref):
            if not (REPO / path).exists():
                return ""
        kind = src.get("kind", "")
        return f"{ref} ({kind})" if kind else ref
    return str(src)


def fmt_quantum(q) -> str:
    if isinstance(q, dict):
        return ", ".join(f"{k} {v}" for k, v in q.items())
    return str(q)


def anchor(name: str) -> str:
    return "m-" + name.replace("_", "-")


def render(metrics: list[dict]) -> str:
    groups: OrderedDict = OrderedDict((k, []) for k in SELECTION_TEXT)
    for m in metrics:
        key = m.get("selected_by")
        if key not in groups:
            groups[key] = []
        groups[key].append(m)
    lines = [BANNER, "# Metric catalogue", ""]
    lines += [
        f"Every metric this build can measure: {len(metrics)} definitions, generated from the "
        "`MetricDef` each provider publishes. A scenario selects metrics with its `metrics:` "
        "list ([Metrics and outputs](../recording-and-metrics.md#metrics)); each section "
        "below says which selection installs its metrics. Visibility `gt` means the metric "
        "is computed from ground truth that no node could observe, `node` that a node "
        "could compute it from what it received, and `node-and-gt` that it joins both. "
        "A health band, where a metric has one, is what `v2xw compare` and the Studio "
        "judge a value against.",
        "",
        '!!! note "Reading a row"',
        "    *Aggregation* is how observations in a window are reduced. *Min samples* is the "
        "count below which a window reports `insufficient` instead of a value. *Does not "
        "account for* is what the definition deliberately leaves out.",
        "",
        "| Section | Metrics |",
        "|---|---|",
    ]
    for key, ms in groups.items():
        if not ms:
            continue
        title = SELECTION_TITLE.get(key, str(key))
        slug = "s-" + (key or "runtime").replace(",", "").replace(".", "-").replace(" ", "-")
        lines.append(f"| [{title}](#{slug}) | {len(ms)} |")
    lines.append("")
    for key, ms in groups.items():
        if not ms:
            continue
        title = SELECTION_TITLE.get(key, str(key))
        slug = "s-" + (key or "runtime").replace(",", "").replace(".", "-").replace(" ", "-")
        lines += [f"## {title} {{ #{slug} }}", "", SELECTION_TEXT.get(key, ""), ""]
        lines += ["| Metric | Unit | Aggregation | Visibility | Definition |", "|---|---|---|---|---|"]
        for m in sorted(ms, key=lambda d: d["name"]):
            first = cell(m.get("definition_md", "")).split(". ")[0].rstrip(".")
            lines.append(
                f"| [`{m['name']}`](#{anchor(m['name'])}) | {cell(m.get('unit', ''))} | "
                f"{cell(fmt_agg(m.get('agg')))} | {cell(m.get('visibility', ''))} | {first} |"
            )
        lines.append("")
        for m in sorted(ms, key=lambda d: d["name"]):
            lines += [f"### `{m['name']}` {{ #{anchor(m['name'])} }}", ""]
            lines += [" ".join(str(m.get("definition_md", "")).split()), ""]
            rows = [
                ("Unit", m.get("unit", "")),
                ("Aggregation", fmt_agg(m.get("agg"))),
                ("Visibility", m.get("visibility", "")),
                ("Dimensions", fmt_dims(m.get("dims"))),
                ("Grid (quantum)", fmt_quantum(m.get("quantum", ""))),
                ("Min samples", m.get("min_samples", "")),
                ("Source", fmt_source(m.get("source"))),
            ]
            if m.get("diagnostic"):
                rows.append(("Diagnostic", "yes: machine-dependent, excluded from digests"))
            h = m.get("health")
            if h:
                rows.append(("Better", f"{h.get('better', '')} ({h.get('basis', '')} basis)"))
                rows.append(("Healthy", h.get("healthy_note", "")))
                rows.append(("Caution", f"{h.get('caution')}: {h.get('caution_note', '')}"))
                rows.append(("Unhealthy", f"{h.get('unhealthy')}: {h.get('unhealthy_note', '')}"))
                rows.append(("Band source", h.get("source", "")))
            lines += ["| Field | Value |", "|---|---|"]
            for k, v in rows:
                if v not in ("", None, []):
                    lines.append(f"| {k} | {cell(v)} |")
            na = m.get("not_accounted") or []
            if na:
                lines += ["", "Does not account for:", ""]
                lines += [f"- {' '.join(str(x).split())}" for x in na]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("input", type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    data = json.loads(args.input.read_text(encoding="utf-8"))
    metrics = data["metrics"]
    names = [m["name"] for m in metrics]
    if len(names) != len(set(names)):
        print("error: a metric name appears twice in the input", file=sys.stderr)
        return 1
    if not metrics:
        print("error: no metrics in the input", file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(sanitize(render(metrics)), encoding="utf-8")
    print(f"wrote {args.out} ({len(metrics)} metrics)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
