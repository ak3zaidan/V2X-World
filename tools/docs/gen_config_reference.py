#!/usr/bin/env python3
"""Generate the configuration reference pages from the engine's published settings.

Usage:

    cargo run -q -p v2xw-engine --example dump_settings -- --out target/docs-settings.json
    python3 tools/docs/gen_config_reference.py target/docs-settings.json [--out docs/configuration/reference]

The input is `v2xw_engine::scenario::publish::surface()` (the same JSON the server returns
from `scenario.schema`). The output is one Markdown page per top-level scenario section,
`models.md` (every registered model's card and parameters), and `index.md` (counts and
links). Every published field appears on exactly one page; the script fails otherwise,
and it fails when a generated page is missing from the `nav` of mkdocs.yml.

Nothing here names a scenario field: the sections, subsections, units, defaults, ranges,
choices, statuses and descriptions all come from the input.

Standard library only.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path
from sanitize import sanitize  # drops pointers to unpublished working notes

REPO = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO / "docs" / "configuration" / "reference"

BANNER = (
    "<!-- GENERATED by tools/docs/gen_config_reference.py from the engine's published "
    "settings surface (crates/v2xw-engine/examples/dump_settings.rs). Do not edit by hand: "
    "change the engine and run `just docs-gen`. -->\n"
)

GENERAL = "General"

STATUS_ICON = {
    "wired": ":material-check-circle:{ title=\"Active\" }",
    "partial": ":material-circle-half-full:{ title=\"Partly active\" }",
    "not-implemented": ":material-circle-outline:{ title=\"Not yet implemented\" }",
    "refused": ":material-filter-check:{ title=\"Only its implemented values load\" }",
    "descriptive": ":material-text:{ title=\"Description\" }",
    "unknown": ":material-help-circle-outline:{ title=\"Unclassified\" }",
}


# ---------------------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------------------


def one_line(text: object) -> str:
    """Collapse whitespace so a value fits in one table cell."""
    if text is None:
        return ""
    return re.sub(r"\s+", " ", str(text)).strip()


def cell(text: object) -> str:
    """Escape free text for a Markdown table cell."""
    s = html.escape(one_line(text), quote=False)
    return s.replace("|", "&#124;")


def code(value: object) -> str:
    """Inline code for a value, safe inside a table cell."""
    if isinstance(value, str):
        s = value
    else:
        s = json.dumps(value, ensure_ascii=False, sort_keys=True)
    s = one_line(s)
    if s == "":
        return '`""`'
    if "|" in s or "`" in s:
        # Inline code cannot hold a table pipe; use an HTML code element instead.
        return "<code>" + html.escape(s, quote=False).replace("|", "&#124;") + "</code>"
    tick = "``" if "`" in s else "`"
    return f"{tick}{s}{tick}"


def fmt_default(value: object) -> str:
    if value is None:
        return "`null`"
    s = json.dumps(value, ensure_ascii=False, sort_keys=True)
    if len(s) > 80:
        return code(s[:77] + "...")
    return code(value)


def anchor(path: str) -> str:
    """A stable HTML id for a setting path."""
    return "s-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def section_of(path: str) -> str:
    """The top-level scenario key a field path belongs to."""
    return re.split(r"[.\[]", path, maxsplit=1)[0]


def subsection_of(field: dict, path: str) -> str:
    """The table a field goes in: the engine's own subgroup label if it publishes one,
    else the second path segment (or the section itself for a top-level scalar)."""
    sub = field.get("x-subgroup")
    if isinstance(sub, dict) and sub.get("label"):
        return str(sub["label"])
    rest = path[len(section_of(path)) :].lstrip(".")
    segments = [seg for seg in rest.split(".") if seg]
    if len(segments) < 2:
        # A direct child of the section (or the section itself): the "General" table.
        return GENERAL
    return segments[0]


def type_of(field: dict) -> str:
    t = field.get("type")
    if isinstance(t, list):
        t = " or ".join(str(x) for x in t)
    t = t or field.get("kind") or ""
    if field.get("x-nullable"):
        t = f"{t}, optional" if t else "optional"
    if field.get("x-rust-type"):
        t = f"{t} ({field['x-rust-type']})" if t else field["x-rust-type"]
    return str(t)


def range_of(field: dict) -> str:
    parts = []
    if "x-range" in field:
        parts.append(cell(field["x-range"]))
    else:
        lo = field.get("minimum", field.get("exclusiveMinimum"))
        hi = field.get("maximum")
        if lo is not None or hi is not None:
            left = "(" if "exclusiveMinimum" in field else "["
            parts.append(f"{left}{'' if lo is None else lo}, {'' if hi is None else hi}]")
    opts = field.get("x-options")
    values: list[str] = []
    if isinstance(opts, list) and opts:
        for o in opts:
            v = o.get("value", o.get("id")) if isinstance(o, dict) else o
            if v is not None:
                values.append(str(v))
    elif isinstance(field.get("enum"), list):
        values = [str(v) for v in field["enum"]]
    if values:
        shown = ", ".join(code(v) for v in values)
        if field.get("x-options-open"):
            shown += " (or another value)"
        parts.append(shown)
    narrowed = field.get("x-enum-narrowed")
    if isinstance(narrowed, dict) and narrowed.get("by"):
        parts.append(
            "narrowed by "
            + code(narrowed["by"])
            + (f" when {cell(narrowed.get('when'))}" if narrowed.get("when") else "")
        )
    if field.get("x-recommended") is not None:
        parts.append("recommended " + cell(_rec(field["x-recommended"])))
    return "<br>".join(parts)


def _rec(rec: object) -> str:
    if isinstance(rec, dict):
        lo, hi = rec.get("lo", rec.get("min")), rec.get("hi", rec.get("max"))
        if lo is not None or hi is not None:
            return f"{lo} to {hi}"
    if isinstance(rec, (list, tuple)) and len(rec) == 2:
        return f"{rec[0]} to {rec[1]}"
    return one_line(json.dumps(rec) if not isinstance(rec, str) else rec)


def description_of(field: dict) -> str:
    title = one_line(field.get("title"))
    desc = one_line(field.get("description"))
    explain = one_line(field.get("x-explain"))
    text = desc or explain
    if explain and desc and explain != desc:
        text = f"{desc} {explain}"
    out = cell(text) if text else cell(title)
    if field.get("x-slot"):
        out += f" Model slot: family {code(field['x-slot'])}, see [model parameters](models.md)."
    rel = field.get("x-relevant-when")
    if isinstance(rel, dict) and rel.get("path"):
        vals = rel.get("in") or []
        out += f" Applies when {code(rel['path'])} is " + ", ".join(code(v) for v in vals) + "."
    status = field.get("x-status", "unknown")
    note = one_line(field.get("x-status-note"))
    if status not in ("wired", "descriptive") and note:
        out += f" *Status: {cell(note)}*"
    return out


def option_details(field: dict) -> list[str]:
    """The labelled choices of a field, when the engine describes them."""
    opts = field.get("x-options")
    if not isinstance(opts, list):
        return []
    rows = []
    for o in opts:
        if not isinstance(o, dict):
            continue
        v = o.get("value", o.get("id"))
        label = one_line(o.get("label"))
        doc = one_line(o.get("description") or o.get("explain") or o.get("doc"))
        if v is None or not (label or doc):
            continue
        rows.append(f"| {code(v)} | {cell(label)} | {cell(doc)} |")
    if not rows:
        return []
    return ["| Value | Label | Meaning |", "|---|---|---|", *rows]


# ---------------------------------------------------------------------------------------
# Pages
# ---------------------------------------------------------------------------------------


def slugify_page(section: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", section.lower()).strip("-") or "section"


def write_section(out: Path, section: str, group: dict | None, fields: list[dict]) -> int:
    subs: OrderedDict[str, list[dict]] = OrderedDict()
    for f in fields:
        subs.setdefault(subsection_of(f, f["x-path"]), []).append(f)
    if GENERAL in subs:
        subs.move_to_end(GENERAL, last=False)
    lines = [BANNER, f"# `{section}`", ""]
    if group:
        lines += [f"Group: **{group['name']}**. {one_line(group.get('description'))}", ""]
    lines += [
        f"{len(fields)} settings. The status column says whether editing a setting changes "
        "a run; see [how to read these tables](../overview.md). Paths use `[]` for a list "
        "element and `*` for a map key.",
        "",
        "| Status | Meaning |",
        "|---|---|",
    ]
    for sid, icon in STATUS_ICON.items():
        if any(f.get("x-status", "unknown") == sid for f in fields):
            lines.append(f"| {icon} | `{sid}` |")
    lines.append("")
    choices: list[tuple[str, list[str]]] = []
    for sub, rows in subs.items():
        title = sub
        blurb = ""
        for r in rows:
            if r.get("x-subgroup-blurb"):
                blurb = one_line(r["x-subgroup-blurb"])
                break
        lines += [f"## {title}", ""]
        if blurb:
            lines += [cell(blurb), ""]
        lines += [
            "| Setting | Type | Unit | Default | Range or choices | Level | Status | Description |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for f in rows:
            path = f["x-path"]
            status = f.get("x-status", "unknown")
            lines.append(
                "| "
                + " | ".join(
                    [
                        f'<span id="{anchor(path)}"></span>{code(path)}',
                        cell(type_of(f)),
                        cell(f.get("unit", "")),
                        fmt_default(f["default"]) if "default" in f else "",
                        range_of(f),
                        cell(f.get("x-level", "")),
                        f"{STATUS_ICON.get(status, '')} `{status}`",
                        description_of(f),
                    ]
                )
                + " |"
            )
            details = option_details(f)
            if details:
                choices.append((path, details))
        lines.append("")
    if choices:
        lines += ["## Choices", "", "The labelled values of every closed or model setting above.", ""]
        for path, details in choices:
            lines += [f'??? note "`{path}`"', ""]
            lines += ["    " + d for d in details]
            lines.append("")
    (out / f"{slugify_page(section)}.md").write_text(sanitize("\n".join(lines).rstrip() + "\n"))
    return len(fields)


def source_text(src: object) -> str:
    """A model-card source (`{kind, ref, note}`) as one line of text."""
    if src is None:
        return ""
    if isinstance(src, str):
        return one_line(src)
    if isinstance(src, dict):
        kind = one_line(src.get("kind"))
        ref = one_line(src.get("ref") or src.get("citation") or src.get("reference"))
        note = one_line(src.get("note"))
        text = f"{kind}: {ref}" if kind and ref else (ref or kind)
        return f"{text}. {note}" if note else text
    return one_line(json.dumps(src, ensure_ascii=False))


def item_text(v: object) -> str:
    """An equation, assumption or limitation of a card as one Markdown list item."""
    if isinstance(v, dict) and ("latex_or_text" in v or "name" in v):
        name = one_line(v.get("name"))
        body = one_line(v.get("latex_or_text"))
        notes = one_line(v.get("notes"))
        out = (f"*{cell(name)}*: " if name else "") + (code(body) if body else "")
        return out + (f" {cell(notes)}" if notes else "")
    if isinstance(v, str):
        return cell(v)
    return cell(json.dumps(v, ensure_ascii=False))


def write_models(out: Path, surface: dict) -> tuple[int, int]:
    models = surface.get("models") or {}
    by_family = models.get("by_family") or {}
    slots = surface.get("slots") or []
    lines = [
        BANNER,
        "# Model parameters",
        "",
        "A scenario selects a model in a *slot* with `{ id, params }`; the parameters a model "
        "accepts are listed on its card. This page is generated from the model registry.",
        "",
    ]
    if slots:
        lines += ["## Slots", "", "| Slot | Family | Selectable ids |", "|---|---|---|"]
        for s in slots:
            ids = s.get("selectable") or s.get("ids") or []
            idlist = ", ".join(
                code(i.get("id") if isinstance(i, dict) else i) for i in ids
            )
            lines.append(
                f"| {code(s.get('path', ''))} | {code(s.get('family', ''))} | {idlist} |"
            )
        lines.append("")
    n_models = 0
    n_params = 0
    for family in sorted(by_family):
        lines += [f"## {family}", ""]
        for m in by_family[family]:
            n_models += 1
            mid = m.get("id", "")
            lines += [f"### `{mid}`", ""]
            facts = [
                f"version {code(m.get('version', ''))}",
                "tiers " + ", ".join(code(t) for t in (m.get("tiers") or [])),
                f"hosting {code(m.get('hosting', ''))}",
            ]
            det = m.get("determinism")
            if isinstance(det, dict) and "uses_rng" in det:
                facts.append("draws random numbers" if det["uses_rng"] else "draws no random numbers")
            lines += [cell(m.get("purpose", "")), "", "; ".join(facts) + ".", ""]
            params = m.get("parameters") or []
            if params:
                lines += [
                    "| Parameter | Unit | Default | Range | Source |",
                    "|---|---|---|---|---|",
                ]
                for p in params:
                    n_params += 1
                    src = source_text(p.get("source"))
                    if p.get("todo_calibrate"):
                        src = (src + " " if src else "") + "(calibration pending)"
                    lines.append(
                        f"| {code(p.get('name', ''))} | {cell(p.get('unit', ''))} | "
                        f"{fmt_default(p.get('default'))} | {cell(p.get('range') or '')} | "
                        f"{cell(src)} |"
                    )
                lines.append("")
            for key, heading in (
                ("equations", "Equations"),
                ("assumptions", "Assumptions"),
                ("limitations", "Limitations"),
                ("ignores", "Ignores"),
            ):
                vals = m.get(key) or []
                if isinstance(vals, str):
                    vals = [vals]
                if vals:
                    lines += [f"**{heading}.**", ""]
                    lines += [f"- {item_text(v)}" for v in vals]
                    lines.append("")
            srcs = m.get("sources") or []
            if srcs:
                lines += ["**Sources.**", ""]
                lines += [f"- {cell(source_text(x))}" for x in srcs]
                lines.append("")
    (out / "models.md").write_text(sanitize("\n".join(lines).rstrip() + "\n"))
    return n_models, n_params


def write_index(out: Path, surface: dict, counts: "OrderedDict[str, int]", groups: dict, n_models: int, n_params: int, statuses: dict) -> None:
    total = sum(counts.values())
    lines = [
        BANNER,
        "# Generated reference",
        "",
        f"**{total} settings** in **{len(counts)} sections**, and **{n_models} registered "
        f"models** with **{n_params} parameters**, published by scenario schema "
        f"`{surface.get('version', '')}`.",
        "",
        "Read the [overview](../overview.md) first for how a row is read.",
        "",
        "| Section | Group | Settings |",
        "|---|---|---|",
    ]
    for section, n in counts.items():
        g = groups.get(section)
        lines.append(f"| [`{section}`]({slugify_page(section)}.md) | {g['name'] if g else ''} | {n} |")
    lines += [f"| [Model parameters](models.md) | Models | {n_params} |", "", "## By status", ""]
    lines += ["| Status | Settings |", "|---|---|"]
    for sid, n in statuses.items():
        lines.append(f"| {STATUS_ICON.get(sid, '')} `{sid}` | {n} |")
    vocab = surface.get("statuses") or []
    if vocab:
        lines += ["", "| Status | Label | Meaning |", "|---|---|---|"]
        for s in vocab:
            lines.append(f"| `{s.get('id')}` | {cell(s.get('label'))} | {cell(s.get('note'))} |")
    (out / "index.md").write_text(sanitize("\n".join(lines).rstrip() + "\n"))


def check_nav(out: Path, pages: list[str]) -> list[str]:
    mk = REPO / "mkdocs.yml"
    if not mk.exists():
        return []
    text = mk.read_text()
    rel = out.relative_to(REPO / "docs").as_posix()
    return [p for p in pages if f"{rel}/{p}" not in text]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("surface", type=Path, help="JSON from the dump_settings example")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    surface = json.loads(args.surface.read_text())
    fields = surface.get("fields")
    if not isinstance(fields, list) or not fields:
        print("error: the input has no `fields` list", file=sys.stderr)
        return 1

    groups: dict[str, dict] = {}
    order: list[str] = []
    for g in surface.get("groups") or []:
        for s in g.get("sections") or []:
            groups[s] = g
            order.append(s)

    # A path can be published more than once when it is a field of several variants of
    # one tagged enum (`world.source.path` under each source kind). It is one setting:
    # the rows are merged, and any key that differs between them must be a description.
    merged: OrderedDict[str, dict] = OrderedDict()
    for f in fields:
        path = f.get("x-path")
        if not path:
            print(f"error: a field has no x-path: {json.dumps(f)[:200]}", file=sys.stderr)
            return 1
        if path not in merged:
            merged[path] = dict(f)
            continue
        first = merged[path]
        for key in set(first) | set(f):
            a, b = first.get(key), f.get(key)
            if a == b:
                continue
            if key in ("description", "x-explain"):
                parts = [x for x in (a, b) if x]
                first[key] = " Or, for another variant: ".join(parts) if a and b else (a or b)
            else:
                print(f"error: `{path}` is published twice with different `{key}`", file=sys.stderr)
                return 1

    by_section: OrderedDict[str, list[dict]] = OrderedDict((s, []) for s in order)
    for path, f in merged.items():
        by_section.setdefault(section_of(path), []).append(f)
    settings = list(merged.values())

    args.out.mkdir(parents=True, exist_ok=True)
    for old in args.out.glob("*.md"):
        old.unlink()

    counts: OrderedDict[str, int] = OrderedDict()
    statuses: OrderedDict[str, int] = OrderedDict()
    for section, rows in by_section.items():
        if not rows:
            continue
        counts[section] = write_section(args.out, section, groups.get(section), rows)
        for r in rows:
            sid = r.get("x-status", "unknown")
            statuses[sid] = statuses.get(sid, 0) + 1
    n_models, n_params = write_models(args.out, surface)
    write_index(args.out, surface, counts, groups, n_models, n_params, statuses)

    # Every field exactly once: count the anchors written.
    written = 0
    for page in args.out.glob("*.md"):
        written += page.read_text().count('<span id="s-')
    if written != len(settings):
        print(f"error: {len(settings)} settings published but {written} rows written", file=sys.stderr)
        return 1

    pages = ["index.md", "models.md", *(f"{slugify_page(s)}.md" for s in counts)]
    missing = check_nav(args.out, pages)
    if missing:
        print(f"error: generated pages missing from the mkdocs.yml nav: {missing}", file=sys.stderr)
        return 1
    print(
        f"{len(settings)} settings ({len(fields)} published rows) in {len(counts)} sections, "
        f"{n_models} models with "
        f"{n_params} parameters -> {args.out}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
