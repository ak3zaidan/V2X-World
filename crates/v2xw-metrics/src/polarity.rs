//! Which way is better, for every metric family: the one table the server's run comparison
//! (`v2xw-server::compare`) and the Studio's `polarityOf` both read.
//!
//! A metric with a health band ([`crate::health::band_for`]) takes the band's direction. The
//! rest are listed here, by family name; a name in neither list falls back to the name hints
//! (`recall`, `delivery`, … → higher is better) and then to lower-is-better (a latency, a loss,
//! a queue). The Studio reads `ui/apps/studio/src/metrics/polarity.generated.json`, which
//! [`studio_table`] writes; the test `studio_table_is_current` fails when the two disagree, and
//! `V2XW_REGEN_POLARITY=1 cargo test -p v2xw-metrics polarity` rewrites the file.

use crate::health::{Better, band_for};
use serde_json::{Value, json};

/// Families with a health band; their direction comes from the band.
pub const BANDED: &[&str] = &[
    "cbr",
    "channel_load",
    "airtime_per_node",
    "mac_queue_depth",
    "mac_access_delay",
    "pdr",
    "nar",
    "aoi",
    "pir",
    "e2e_latency",
    "verify_wait",
    "verify_queue_depth",
    "unverified_ratio",
    "cert_pool_valid",
    "revocation_latency_stage",
    "det_recall",
    "det_fpr",
    "linkability",
    "backend_link_up",
    "ttc_min",
    "drac",
];

/// Larger is better.
pub const HIGHER: &[&str] = &[
    "pdr",
    "pdr_all_pairs",
    "delivery_ratio",
    "goodput",
    "nar",
    "det_recall",
    "det_precision",
    "det_accuracy",
    "det_f1",
    "ttc_min",
    "pet",
    "headway_time",
    "headway_distance",
    "cert_pool_valid",
    "backend_link_up",
    "carried_load",
    // More warning time before a conflict is better (SAE J2945/1 warning timing).
    "app_lead_time_s",
    "app_precision",
    // A pedestrian's time to collision, as `ttc_min` for vehicles.
    "ped_ttc",
    // The lowest battery state of charge in the fleet: higher is further from depletion.
    "ev_soc_min",
];

/// Neither direction is better: a speed, a flow, a rate of protocol activity, a share.
pub const NEUTRAL: &[&str] = &[
    "mean_speed",
    "speed",
    "acceleration",
    "flow",
    "density",
    "offered_load",
    "verify_rate",
    "crl_entries",
    "pseudonym_change_rate",
    "events_processed",
    "events_per_second",
    "bytes_total",
    // P2PCD learning requests (IEEE 1609.2 clause 8) and digest misses (digest-signed
    // messages from signers not yet cached, named `p2pcd_requests` before 2026-10-25)
    // follow pseudonym changes and new neighbours, so a higher rate means more churn, not
    // a worse network. They were lower-is-better by default before.
    "p2pcd_requests",
    "digest_misses",
    // The full-certificate share is a policy (SAE J2945/1 sends the full certificate once a
    // second or to a new neighbour): a trade between overhead and verifiability.
    "full_cert_share",
    // Counts and shares, not quality.
    "latency_stage_share",
    "app_warnings",
    "ped_midblock_share",
];

/// Substrings of a family name that mean larger is better, when it is in neither list.
pub const HIGHER_HINTS: &[&str] = &[
    "recall",
    "precision",
    "accuracy",
    "delivery",
    "pdr",
    "availability",
];

/// Which way is better for a metric family; `None` is neutral.
#[must_use]
pub fn better_of(base: &str) -> Option<Better> {
    if let Some(b) = band_for(base) {
        return Some(b.better);
    }
    if HIGHER.contains(&base) {
        return Some(Better::Higher);
    }
    if NEUTRAL.contains(&base) {
        return None;
    }
    if HIGHER_HINTS.iter().any(|k| base.contains(k)) || base.ends_with("_up") {
        return Some(Better::Higher);
    }
    Some(Better::Lower)
}

fn word(b: Option<Better>) -> &'static str {
    match b {
        Some(Better::Higher) => "higher-better",
        Some(Better::Lower) => "lower-better",
        None => "neutral",
    }
}

/// The table the Studio reads: every listed family's resolved polarity, and the fallback rules.
#[must_use]
pub fn studio_table() -> Value {
    let mut families = serde_json::Map::new();
    for name in BANDED.iter().chain(HIGHER).chain(NEUTRAL) {
        families.insert((*name).to_string(), json!(word(better_of(name))));
    }
    json!({
        "comment": "Generated by v2xw-metrics polarity::studio_table; do not edit. Regenerate with V2XW_REGEN_POLARITY=1 cargo test -p v2xw-metrics polarity",
        "families": families,
        "higherHints": HIGHER_HINTS,
        "higherSuffix": "_up",
        "fallback": "lower-better",
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_banded_family_has_a_band() {
        for name in BANDED {
            assert!(band_for(name).is_some(), "{name} has no band");
        }
    }

    #[test]
    fn studio_table_is_current() {
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../ui/apps/studio/src/metrics/polarity.generated.json"
        );
        let want = format!(
            "{}\n",
            serde_json::to_string_pretty(&studio_table()).unwrap()
        );
        if std::env::var_os("V2XW_REGEN_POLARITY").is_some() {
            std::fs::write(path, &want).unwrap();
        }
        let have = std::fs::read_to_string(path).unwrap_or_default();
        assert_eq!(have, want, "stale; rerun with V2XW_REGEN_POLARITY=1");
    }

    #[test]
    fn debatable_entries() {
        assert_eq!(better_of("p2pcd_requests"), None);
        assert_eq!(better_of("digest_misses"), None);
        assert_eq!(better_of("app_lead_time_s"), Some(Better::Higher));
        assert_eq!(better_of("e2e_latency"), Some(Better::Lower));
    }
}
